CREATE EXTENSION IF NOT EXISTS btree_gist;

CREATE TABLE establecimiento (
    id_establecimiento BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(120) NOT NULL,
    nit VARCHAR(20) NOT NULL UNIQUE,
    tipo VARCHAR(20) NOT NULL CHECK (tipo IN ('BARBERIA', 'PELUQUERIA', 'SPA', 'SALON_UNAS')),
    direccion VARCHAR(200) NOT NULL,
    ciudad VARCHAR(80) NOT NULL,
    telefono VARCHAR(20) NOT NULL,
    zona_horaria VARCHAR(40) NOT NULL DEFAULT 'America/Bogota',
    anticipacion_min_horas INT NOT NULL DEFAULT 2 CHECK (anticipacion_min_horas >= 0),
    estado VARCHAR(15) NOT NULL DEFAULT 'ACTIVO' CHECK (estado IN ('ACTIVO', 'SUSPENDIDO'))
);

CREATE TABLE usuario (
    id_usuario BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombres VARCHAR(80) NOT NULL,
    apellidos VARCHAR(80) NOT NULL,
    correo VARCHAR(150) UNIQUE,
    telefono VARCHAR(20) NOT NULL UNIQUE,
    hash_clave VARCHAR(100),
    rol VARCHAR(15) NOT NULL CHECK (rol IN ('CLIENTE', 'PROFESIONAL', 'ADMINISTRADOR')),
    estado VARCHAR(15) NOT NULL DEFAULT 'ACTIVO' CHECK (estado IN ('ACTIVO', 'BLOQUEADO', 'INACTIVO')),
    intentos_fallidos INT NOT NULL DEFAULT 0 CHECK (intentos_fallidos >= 0),
    bloqueado_hasta TIMESTAMP,
    fecha_registro TIMESTAMP NOT NULL DEFAULT now(),
    CONSTRAINT ck_usuario_acceso CHECK (rol = 'CLIENTE' OR (correo IS NOT NULL AND hash_clave IS NOT NULL))
);

CREATE TABLE cliente (
    id_usuario BIGINT PRIMARY KEY REFERENCES usuario(id_usuario) ON DELETE CASCADE,
    fecha_nacimiento DATE,
    preferencias VARCHAR(500),
    autoriza_tratamiento_datos BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE administrador (
    id_usuario BIGINT PRIMARY KEY REFERENCES usuario(id_usuario) ON DELETE CASCADE,
    id_establecimiento BIGINT REFERENCES establecimiento(id_establecimiento),
    cargo VARCHAR(25) NOT NULL CHECK (cargo IN ('PROPIETARIO', 'RECEPCIONISTA', 'RESPONSABLE_INVENTARIO', 'ADMIN_PLATAFORMA'))
);

CREATE TABLE profesional (
    id_usuario BIGINT PRIMARY KEY REFERENCES usuario(id_usuario) ON DELETE CASCADE,
    id_establecimiento BIGINT NOT NULL REFERENCES establecimiento(id_establecimiento),
    especialidad VARCHAR(80) NOT NULL,
    calificacion_promedio NUMERIC(2,1) NOT NULL DEFAULT 0 CHECK (calificacion_promedio BETWEEN 0 AND 5),
    activo BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE servicio (
    id_servicio BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_establecimiento BIGINT NOT NULL REFERENCES establecimiento(id_establecimiento),
    nombre VARCHAR(100) NOT NULL,
    categoria VARCHAR(20) NOT NULL CHECK (categoria IN ('CABELLO', 'BARBA', 'UNAS', 'TRATAMIENTOS', 'COMBO')),
    descripcion VARCHAR(300),
    duracion_min INT NOT NULL CHECK (duracion_min > 0),
    precio NUMERIC(12,2) NOT NULL CHECK (precio > 0),
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT uq_servicio_nombre UNIQUE (id_establecimiento, nombre)
);

CREATE TABLE profesional_servicio (
    id_profesional BIGINT NOT NULL REFERENCES profesional(id_usuario) ON DELETE CASCADE,
    id_servicio BIGINT NOT NULL REFERENCES servicio(id_servicio) ON DELETE CASCADE,
    PRIMARY KEY (id_profesional, id_servicio)
);

CREATE TABLE horario (
    id_horario BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_profesional BIGINT NOT NULL REFERENCES profesional(id_usuario) ON DELETE CASCADE,
    dia_semana VARCHAR(10) NOT NULL CHECK (dia_semana IN ('MONDAY', 'TUESDAY', 'WEDNESDAY', 'THURSDAY', 'FRIDAY', 'SATURDAY', 'SUNDAY')),
    hora_inicio TIME NOT NULL,
    hora_fin TIME NOT NULL,
    descanso_inicio TIME,
    descanso_fin TIME,
    vigente_desde DATE NOT NULL,
    CONSTRAINT ck_horario_jornada CHECK (hora_fin > hora_inicio),
    CONSTRAINT ck_horario_descanso CHECK ((descanso_inicio IS NULL AND descanso_fin IS NULL) OR (descanso_inicio IS NOT NULL AND descanso_fin IS NOT NULL AND descanso_fin > descanso_inicio AND descanso_inicio >= hora_inicio AND descanso_fin <= hora_fin))
);

CREATE TABLE cita (
    id_cita BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cliente BIGINT NOT NULL REFERENCES cliente(id_usuario),
    id_profesional BIGINT NOT NULL REFERENCES profesional(id_usuario),
    id_establecimiento BIGINT NOT NULL REFERENCES establecimiento(id_establecimiento),
    fecha_hora_inicio TIMESTAMP NOT NULL,
    fecha_hora_fin TIMESTAMP NOT NULL,
    estado VARCHAR(15) NOT NULL DEFAULT 'PROGRAMADA' CHECK (estado IN ('PROGRAMADA', 'CONFIRMADA', 'EN_ATENCION', 'FINALIZADA', 'CANCELADA', 'NO_ASISTIO')),
    valor_estimado NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (valor_estimado >= 0),
    observaciones VARCHAR(500),
    motivo_cancelacion VARCHAR(200),
    fecha_creacion TIMESTAMP NOT NULL DEFAULT now(),
    CONSTRAINT ck_cita_rango CHECK (fecha_hora_fin > fecha_hora_inicio)
);

CREATE TABLE detalle_cita (
    id_detalle BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cita BIGINT NOT NULL REFERENCES cita(id_cita) ON DELETE CASCADE,
    id_servicio BIGINT NOT NULL REFERENCES servicio(id_servicio),
    precio_aplicado NUMERIC(12,2) NOT NULL CHECK (precio_aplicado >= 0),
    duracion_min INT NOT NULL CHECK (duracion_min > 0)
);

CREATE TABLE notificacion (
    id_notificacion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cita BIGINT NOT NULL REFERENCES cita(id_cita) ON DELETE CASCADE,
    id_usuario BIGINT NOT NULL REFERENCES usuario(id_usuario),
    tipo VARCHAR(20) NOT NULL CHECK (tipo IN ('CONFIRMACION', 'RECORDATORIO_24H', 'RECORDATORIO_2H', 'MODIFICACION', 'CANCELACION')),
    canal VARCHAR(10) NOT NULL CHECK (canal IN ('EMAIL', 'SMS')),
    mensaje VARCHAR(500) NOT NULL,
    fecha_programada TIMESTAMP NOT NULL,
    estado_envio VARCHAR(12) NOT NULL DEFAULT 'PENDIENTE' CHECK (estado_envio IN ('PENDIENTE', 'ENVIADA', 'FALLIDA')),
    intentos INT NOT NULL DEFAULT 0 CHECK (intentos BETWEEN 0 AND 3)
);

CREATE TABLE promocion (
    id_promocion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_establecimiento BIGINT NOT NULL REFERENCES establecimiento(id_establecimiento),
    codigo VARCHAR(30) NOT NULL,
    tipo_descuento VARCHAR(12) NOT NULL CHECK (tipo_descuento IN ('PORCENTAJE', 'MONTO_FIJO')),
    valor NUMERIC(12,2) NOT NULL CHECK (valor > 0),
    vigencia_desde DATE NOT NULL,
    vigencia_hasta DATE NOT NULL,
    activa BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT ck_promocion_vigencia CHECK (vigencia_hasta >= vigencia_desde),
    CONSTRAINT ck_promocion_porcentaje CHECK (tipo_descuento <> 'PORCENTAJE' OR valor <= 100),
    CONSTRAINT uq_promocion_codigo UNIQUE (id_establecimiento, codigo)
);

CREATE TABLE pago (
    id_pago BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cita BIGINT NOT NULL REFERENCES cita(id_cita),
    id_promocion BIGINT REFERENCES promocion(id_promocion),
    id_registrado_por BIGINT NOT NULL REFERENCES usuario(id_usuario),
    subtotal NUMERIC(12,2) NOT NULL CHECK (subtotal >= 0),
    descuento NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (descuento >= 0),
    valor_cobrado NUMERIC(12,2) NOT NULL CHECK (valor_cobrado >= 0),
    metodo_pago VARCHAR(15) NOT NULL CHECK (metodo_pago IN ('EFECTIVO', 'TARJETA', 'TRANSFERENCIA', 'BILLETERA')),
    referencia VARCHAR(60),
    fecha_pago TIMESTAMP NOT NULL DEFAULT now(),
    estado VARCHAR(12) NOT NULL DEFAULT 'PENDIENTE' CHECK (estado IN ('PENDIENTE', 'APROBADO', 'RECHAZADO', 'ANULADO')),
    CONSTRAINT ck_pago_valor CHECK (valor_cobrado = subtotal - descuento)
);

CREATE TABLE regla_comision (
    id_regla BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_establecimiento BIGINT NOT NULL REFERENCES establecimiento(id_establecimiento),
    id_profesional BIGINT REFERENCES profesional(id_usuario),
    id_servicio BIGINT REFERENCES servicio(id_servicio),
    porcentaje_profesional NUMERIC(5,2) NOT NULL CHECK (porcentaje_profesional BETWEEN 0 AND 100),
    porcentaje_establecimiento NUMERIC(5,2) NOT NULL CHECK (porcentaje_establecimiento BETWEEN 0 AND 100),
    descontar_insumos BOOLEAN NOT NULL DEFAULT FALSE,
    vigente_desde DATE NOT NULL,
    vigente_hasta DATE,
    CONSTRAINT ck_regla_suma100 CHECK (porcentaje_profesional + porcentaje_establecimiento = 100),
    CONSTRAINT ck_regla_vigencia CHECK (vigente_hasta IS NULL OR vigente_hasta >= vigente_desde)
);

CREATE TABLE comision (
    id_comision BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pago BIGINT NOT NULL UNIQUE REFERENCES pago(id_pago),
    id_profesional BIGINT NOT NULL REFERENCES profesional(id_usuario),
    id_regla BIGINT NOT NULL REFERENCES regla_comision(id_regla),
    base_comision NUMERIC(12,2) NOT NULL CHECK (base_comision >= 0),
    costo_insumos NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (costo_insumos >= 0),
    valor_profesional NUMERIC(12,2) NOT NULL CHECK (valor_profesional >= 0),
    valor_establecimiento NUMERIC(12,2) NOT NULL CHECK (valor_establecimiento >= 0),
    estado_liquidacion VARCHAR(12) NOT NULL DEFAULT 'PENDIENTE' CHECK (estado_liquidacion IN ('PENDIENTE', 'LIQUIDADA'))
);

CREATE TABLE transaccion (
    id_transaccion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_establecimiento BIGINT NOT NULL REFERENCES establecimiento(id_establecimiento),
    id_pago BIGINT REFERENCES pago(id_pago),
    id_usuario BIGINT NOT NULL REFERENCES usuario(id_usuario),
    tipo VARCHAR(10) NOT NULL CHECK (tipo IN ('INGRESO', 'EGRESO', 'COMISION', 'AJUSTE')),
    concepto VARCHAR(150) NOT NULL,
    monto NUMERIC(12,2) NOT NULL CHECK (monto > 0),
    fecha TIMESTAMP NOT NULL DEFAULT now()
);

CREATE TABLE fidelizacion (
    id_fidelizacion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cliente BIGINT NOT NULL REFERENCES cliente(id_usuario),
    id_establecimiento BIGINT NOT NULL REFERENCES establecimiento(id_establecimiento),
    puntos_acumulados INT NOT NULL DEFAULT 0 CHECK (puntos_acumulados >= 0),
    puntos_redimidos INT NOT NULL DEFAULT 0 CHECK (puntos_redimidos >= 0),
    nivel VARCHAR(10) NOT NULL DEFAULT 'BRONCE' CHECK (nivel IN ('BRONCE', 'PLATA', 'ORO')),
    fecha_ultimo_movimiento DATE,
    CONSTRAINT ck_fid_saldo CHECK (puntos_redimidos <= puntos_acumulados),
    CONSTRAINT uq_fid_cliente_est UNIQUE (id_cliente, id_establecimiento)
);

CREATE TABLE inventario (
    id_inventario BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_establecimiento BIGINT NOT NULL UNIQUE REFERENCES establecimiento(id_establecimiento),
    ubicacion VARCHAR(100),
    fecha_ultimo_conteo DATE
);

CREATE TABLE insumo (
    id_insumo BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_inventario BIGINT NOT NULL REFERENCES inventario(id_inventario),
    nombre VARCHAR(100) NOT NULL,
    unidad_medida VARCHAR(10) NOT NULL,
    existencias NUMERIC(12,3) NOT NULL DEFAULT 0 CHECK (existencias >= 0),
    stock_minimo NUMERIC(12,3) NOT NULL DEFAULT 0 CHECK (stock_minimo >= 0),
    costo_unitario NUMERIC(12,2) NOT NULL CHECK (costo_unitario >= 0),
    estado VARCHAR(12) NOT NULL DEFAULT 'ACTIVO' CHECK (estado IN ('ACTIVO', 'EN_REVISION', 'INACTIVO')),
    CONSTRAINT uq_insumo_nombre UNIQUE (id_inventario, nombre)
);

CREATE TABLE servicio_insumo (
    id_servicio BIGINT NOT NULL REFERENCES servicio(id_servicio) ON DELETE CASCADE,
    id_insumo BIGINT NOT NULL REFERENCES insumo(id_insumo) ON DELETE CASCADE,
    cantidad_estandar NUMERIC(12,3) NOT NULL CHECK (cantidad_estandar > 0),
    PRIMARY KEY (id_servicio, id_insumo)
);

CREATE TABLE consumo_insumo (
    id_consumo BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cita BIGINT NOT NULL REFERENCES cita(id_cita),
    id_insumo BIGINT NOT NULL REFERENCES insumo(id_insumo),
    cantidad NUMERIC(12,3) NOT NULL CHECK (cantidad > 0),
    costo_total NUMERIC(12,2) NOT NULL CHECK (costo_total >= 0),
    fecha_consumo TIMESTAMP NOT NULL DEFAULT now()
);

CREATE TABLE movimiento_inventario (
    id_movimiento BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_insumo BIGINT NOT NULL REFERENCES insumo(id_insumo),
    id_consumo BIGINT UNIQUE REFERENCES consumo_insumo(id_consumo),
    id_usuario BIGINT NOT NULL REFERENCES usuario(id_usuario),
    tipo VARCHAR(10) NOT NULL CHECK (tipo IN ('ENTRADA', 'CONSUMO', 'AJUSTE')),
    cantidad NUMERIC(12,3) NOT NULL CHECK (cantidad <> 0),
    saldo_resultante NUMERIC(12,3) NOT NULL CHECK (saldo_resultante >= 0),
    fecha TIMESTAMP NOT NULL DEFAULT now()
);

